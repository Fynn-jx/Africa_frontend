export function getDatasetById(id: string | null) {
  if (!id) return null;
  return datasetCatalog.find((dataset) => dataset.id === id) ?? null;
}

export function getDatasetsByLayer(layer: DatasetLayer) {
  return datasetCatalog.filter((dataset) => dataset.layer === layer);
}
